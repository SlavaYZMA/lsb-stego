# ================================================
#   encode.py — прячем текст в картинку
#   Алгоритм: LSB-стеганография (красный канал)
# ================================================
#
#   КАК ЗАПУСТИТЬ:
#   python encode.py
#
#   ЧТО ПОМЕНЯТЬ ПОД СЕБЯ — только эти три строки:

ВХОДНОЙ_ФАЙЛ  = r"C:\Users\1509sadik\Desktop\steno\first.png"   # исходная картинка
ВЫХОДНОЙ_ФАЙЛ = r"C:\Users\1509sadik\Desktop\steno\secret.png"  # куда сохранить результат
СООБЩЕНИЕ     = "сегодня в 22 у башни"                           # текст который хочешь спрятать

# ================================================
#   НИЖЕ НИЧЕГО МЕНЯТЬ НЕ НУЖНО
# ================================================

from PIL import Image  # pip install Pillow
import sys

СТОП_МАРКЕР = "###END###"  # метка конца сообщения — декодер ищет её


def текст_в_биты(текст):
    """Переводим текст в список нулей и единиц через UTF-8 (нужно для кириллицы)."""
    байты = текст.encode("utf-8")  # "привет" → b'\xd0\xbf\xd1\x80\xd0\xb8\xd0\xb2\xd0\xb5\xd1\x82'
    биты = []
    for байт in байты:
        for позиция in range(7, -1, -1):          # берём каждый бит, от старшего к младшему
            биты.append((байт >> позиция) & 1)    # 0 или 1
    return биты


# — Загружаем картинку —
try:
    картинка = Image.open(ВХОДНОЙ_ФАЙЛ).convert("RGB")
except FileNotFoundError:
    print(f"[ОШИБКА] Файл не найден: {ВХОДНОЙ_ФАЙЛ}")
    print("         Проверь путь в переменной ВХОДНОЙ_ФАЙЛ")
    sys.exit(1)

ширина, высота = картинка.size
пикселей_всего = ширина * высота

# — Готовим данные для записи —
полный_текст = СООБЩЕНИЕ + СТОП_МАРКЕР   # добавляем маркер конца
биты = текст_в_биты(полный_текст)         # переводим всё в биты

if len(биты) > пикселей_всего:
    print(f"[ОШИБКА] Сообщение слишком длинное!")
    print(f"         Нужно пикселей: {len(биты)}, а в картинке: {пикселей_всего}")
    sys.exit(1)

# — Записываем биты в пиксели —
новые_пиксели = []
индекс = 0

for y in range(высота):
    for x in range(ширина):
        r, g, b = картинка.getpixel((x, y))

        if индекс < len(биты):
            # Меняем только последний бит красного канала
            # Например: 11001101 → 11001100 или 11001101 (меняем лишь последний бит)
            r = (r & 0b11111110) | биты[индекс]
            индекс += 1

        новые_пиксели.append((r, g, b))

# — Сохраняем результат —
результат = Image.new("RGB", (ширина, высота))
результат.putdata(новые_пиксели)
результат.save(ВЫХОДНОЙ_ФАЙЛ, format="PNG")  # только PNG — JPEG уничтожит скрытые биты!

print(f"[OK] Готово! Сообщение спрятано в картинке.")
print(f"     Сообщение      : «{СООБЩЕНИЕ}»")
print(f"     Результат      : {ВЫХОДНОЙ_ФАЙЛ}")
print(f"     Использовано   : {len(биты)} пикселей из {пикселей_всего}")
