#   ЧТО ПОМЕНЯТЬ ПОД СЕБЯ — только эти три строки:

ВХОДНОЙ_ФАЙЛ  = r"C:\Users\1509sadik\Desktop\steno\first.png"    # исходная картинка
ВЫХОДНОЙ_ФАЙЛ = r"C:\Users\1509sadik\Desktop\steno\secret.png"   # куда сохранить результат
ФАЙЛ_ТЕКСТА   = r"C:\Users\1509sadik\Desktop\steno\message.txt"  # txt-файл с сообщением

# ================================================
#   НИЖЕ НИЧЕГО МЕНЯТЬ НЕ НУЖНО
# ================================================

from PIL import Image
import sys
import math

СТОП_МАРКЕР = "###END###"  # метка конца сообщения — декодер ищет её


def текст_в_биты(текст):
    """Переводим текст в список нулей и единиц через UTF-8 (нужно для кириллицы)."""
    байты = текст.encode("utf-8")
    биты = []
    for байт in байты:
        for позиция in range(7, -1, -1):
            биты.append((байт >> позиция) & 1)
    return биты


# — Читаем текст из файла —
try:
    with open(ФАЙЛ_ТЕКСТА, "r", encoding="utf-8") as ф:
        СООБЩЕНИЕ = ф.read()
except FileNotFoundError:
    print(f"[ОШИБКА] Файл с текстом не найден: {ФАЙЛ_ТЕКСТА}")
    print("         Создай файл message.txt рядом со скриптом и вставь туда текст.")
    sys.exit(1)

if not СООБЩЕНИЕ.strip():
    print(f"[ОШИБКА] Файл {ФАЙЛ_ТЕКСТА} пустой — добавь текст.")
    sys.exit(1)

print(f"[INFO] Текст загружен: {len(СООБЩЕНИЕ):,} символов")

# — Загружаем картинку —
try:
    картинка = Image.open(ВХОДНОЙ_ФАЙЛ).convert("RGB")
except FileNotFoundError:
    print(f"[ОШИБКА] Картинка не найдена: {ВХОДНОЙ_ФАЙЛ}")
    print("         Проверь путь в переменной ВХОДНОЙ_ФАЙЛ")
    sys.exit(1)

ширина, высота = картинка.size
пикселей_всего = ширина * высота

# — Считаем сколько нужно пикселей —
полный_текст = СООБЩЕНИЕ + СТОП_МАРКЕР
биты = текст_в_биты(полный_текст)
нужно_пикселей = len(биты)

print(f"[INFO] Картинка         : {ширина}×{высота} = {пикселей_всего:,} пикселей")
print(f"[INFO] Нужно пикселей   : {нужно_пикселей:,} ({нужно_пикселей*100//пикселей_всего}% от картинки)")

# — Проверка: влезает ли текст —
if нужно_пикселей > пикселей_всего:
    не_хватает = нужно_пикселей - пикселей_всего

    # Минимальное разрешение при том же соотношении сторон
    соотношение = ширина / высота
    мин_высота = math.ceil(math.sqrt(нужно_пикселей / соотношение))
    мин_ширина = math.ceil(мин_высота * соотношение)
    while мин_ширина * мин_высота < нужно_пикселей:
        мин_ширина += 1

    # Стандартные разрешения для сравнения
    варианты = [
        ("HD",      1280,  720),
        ("Full HD", 1920, 1080),
        ("2K",      2560, 1440),
        ("4K",      3840, 2160),
    ]

    print()
    print(f"[ОШИБКА] Текст не влезает в картинку!")
    print(f"         Символов в тексте : {len(СООБЩЕНИЕ):,}")
    print(f"         Нужно пикселей    : {нужно_пикселей:,}")
    print(f"         Есть пикселей     : {пикселей_всего:,}  ({ширина}×{высота})")
    print(f"         Не хватает        : {не_хватает:,} пикселей")
    print()
    print(f"         Минимальное разрешение для твоего текста")
    print(f"         (при соотношении сторон как у текущей картинки):")
    print(f"         → {мин_ширина}×{мин_высота} пикселей")
    print()
    print(f"         Или возьми одно из стандартных разрешений:")
    for название, ш, в in варианты:
        пикс = ш * в
        статус = "✓ подходит" if пикс >= нужно_пикселей else "✗ мало"
        print(f"         {название:8} {ш}×{в} = {пикс:,} пикс — {статус}")
    sys.exit(1)

# — Записываем биты в пиксели —
новые_пиксели = []
индекс = 0

for y in range(высота):
    for x in range(ширина):
        r, g, b = картинка.getpixel((x, y))
        if индекс < len(биты):
            r = (r & 0b11111110) | биты[индекс]
            индекс += 1
        новые_пиксели.append((r, g, b))

# — Сохраняем результат —
результат = Image.new("RGB", (ширина, высота))
результат.putdata(новые_пиксели)
результат.save(ВЫХОДНОЙ_ФАЙЛ, format="PNG")

свободно = пикселей_всего - нужно_пикселей
print(f"[OK] Готово! Сообщение спрятано в картинке.")
print(f"     Символов в тексте : {len(СООБЩЕНИЕ):,}")
print(f"     Результат          : {ВЫХОДНОЙ_ФАЙЛ}")
print(f"     Использовано       : {нужно_пикселей:,} пикселей из {пикселей_всего:,} ({нужно_пикселей*100//пикселей_всего}%)")
print(f"     Свободно осталось  : {свободно:,} пикселей")
