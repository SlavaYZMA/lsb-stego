ФАЙЛ         = r"C:\Users\1509sadik\Desktop\steno\secret.png"        # картинка со спрятанным текстом
ФАЙЛ_ВЫВОДА  = r"C:\Users\1509sadik\Desktop\steno\decoded_message.txt"  # куда сохранить расшифрованный текст

# ================================================
#   НИЖЕ НИЧЕГО МЕНЯТЬ НЕ НУЖНО
# ================================================

from PIL import Image  # pip install Pillow
import sys

СТОП_МАРКЕР = "###END###"  # та же метка что и в encode.py


def биты_в_текст(биты):
    """Собираем байты из бит и декодируем UTF-8 обратно в текст."""
    байты = []
    for i in range(0, len(биты), 8):
        группа = биты[i:i + 8]
        if len(группа) < 8:
            break
        байт = 0
        for бит in группа:
            байт = (байт << 1) | бит
        байты.append(байт)
    return bytes(байты).decode("utf-8", errors="replace")


# — Загружаем картинку —
try:
    картинка = Image.open(ФАЙЛ).convert("RGB")
except FileNotFoundError:
    print(f"[ОШИБКА] Файл не найден: {ФАЙЛ}")
    print("         Проверь путь в переменной ФАЙЛ")
    sys.exit(1)

ширина, высота = картинка.size
print(f"[INFO] Картинка загружена: {ширина}×{высота} пикселей")
print(f"[INFO] Считываем биты из красного канала...")

# — Считываем LSB из красного канала каждого пикселя —
биты = []
for y in range(высота):
    for x in range(ширина):
        r, g, b = картинка.getpixel((x, y))
        биты.append(r & 1)

print(f"[INFO] Биты считаны, ищем сообщение...")

# — Ищем стоп-маркер —
стоп_биты = []
for байт in СТОП_МАРКЕР.encode("utf-8"):
    for позиция in range(7, -1, -1):
        стоп_биты.append((байт >> позиция) & 1)

длина_стопа = len(стоп_биты)
позиция_конца = None

for i in range(len(биты) - длина_стопа + 1):
    if биты[i:i + длина_стопа] == стоп_биты:
        позиция_конца = i
        break

if позиция_конца is None:
    print("[ОШИБКА] Скрытый текст не найден.")
    print("         Возможно, эта картинка не содержит спрятанного сообщения.")
    sys.exit(1)

# — Декодируем биты до маркера —
сообщение = биты_в_текст(биты[:позиция_конца])

# — Сохраняем в txt —
try:
    with open(ФАЙЛ_ВЫВОДА, "w", encoding="utf-8") as ф:
        ф.write(сообщение)
    print(f"[OK] Сообщение найдено и сохранено!")
    print(f"     Символов  : {len(сообщение)}")
    print(f"     Сохранено : {ФАЙЛ_ВЫВОДА}")
    print(f"     Превью    : «{сообщение[:100]}{'...' if len(сообщение) > 100 else ''}»")
except Exception as e:
    print(f"[ОШИБКА] Не удалось сохранить файл: {e}")
    print(f"         Текст (первые 200 символов): {сообщение[:200]}")
    sys.exit(1)
